//! `html::res` against the linked Lexbor, while it is linked.
//!
//! `html::res::names` is still generated here, from Lexbor's static tables:
//! the constant names from the enum headers (`tag/const.h`,
//! `dom/interfaces/attr_const.h`, `ns/const.h`) and each id's strings from
//! the linked Lexbor itself. The other two are generated without Lexbor, by
//! `conformance::res_gen` - `tree` from the HTML Standard, `entities` from
//! the WHATWG `entities.json` - and only compared with Lexbor's tables here
//! (`tag_res.h`, `tree_res.h`, `tokenizer/res.h`).
//!
//! `names_are_lexbors` fails when `names.rs` is not what the generator makes
//! now; `MAKIRI_REGENERATE=1` rewrites it instead.

#![allow(unsafe_code)]
#![allow(clippy::disallowed_methods)]

use crate::conformance::res_gen::lit;
use crate::html::res::{entities, names, SbstEntry};
use crate::lexbor::abi as lxb;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn lexbor_src(rel: &str) -> PathBuf {
    root()
        .join("../../../vendor/lexbor/source/lexbor")
        .join(rel)
}

/// `NAME = 0x00NN` pairs of the enum whose constants start with `prefix`.
fn enum_consts(header: &Path, prefix: &str) -> Vec<(String, usize)> {
    let text = std::fs::read_to_string(header).expect("read a Lexbor header");
    text.lines()
        .filter_map(|l| {
            let l = l.trim().trim_end_matches(',');
            let (name, value) = l.split_once('=')?;
            let name = name.trim().strip_prefix(prefix)?;
            let value = value.trim().strip_prefix("0x")?;
            Some((name.to_string(), usize::from_str_radix(value, 16).ok()?))
        })
        .collect()
}

/// The string of a Lexbor hash entry.
///
/// # Safety
/// `e` is a live entry.
unsafe fn entry_str(e: &lxb::lexbor_hash_entry_t) -> Vec<u8> {
    // SAFETY: the function's contract; an entry keeps a string up to
    // LEXBOR_HASH_SHORT_SIZE (16) inline and a longer one by pointer.
    unsafe {
        if e.length <= 16 {
            e.u.short_str[..e.length].to_vec()
        } else {
            core::slice::from_raw_parts(e.u.long_str, e.length).to_vec()
        }
    }
}

/// One constant block: `pub const PREFIX_NAME: usize = N;` per enum entry.
fn consts(out: &mut String, rust_prefix: &str, entries: &[(String, usize)]) {
    for (name, v) in entries {
        let _ = writeln!(out, "pub const {rust_prefix}{name}: usize = {v};");
    }
}

fn generate_names() -> String {
    let tags = enum_consts(&lexbor_src("tag/const.h"), "LXB_TAG_");
    let attrs = enum_consts(&lexbor_src("dom/interfaces/attr_const.h"), "LXB_DOM_ATTR_");
    let nss = enum_consts(&lexbor_src("ns/const.h"), "LXB_NS_");
    let last = |v: &[(String, usize)]| {
        v.iter()
            .find(|(n, _)| n == "_LAST_ENTRY")
            .map(|(_, v)| *v)
            .expect("a _LAST_ENTRY")
    };
    let (tag_last, attr_last, ns_last) = (last(&tags), last(&attrs), last(&nss));
    let mut out = String::from(
        "//! GENERATED by `lexbor::res_tests` from Lexbor's static name tables - do not edit.\n\
         //! Ids are Lexbor's: `TAG_*` from `tag/const.h`, `ATTR_*` from\n\
         //! `dom/interfaces/attr_const.h`, `NS_*` from `ns/const.h`.\n\n",
    );
    consts(&mut out, "TAG_", &tags);
    out.push('\n');
    consts(&mut out, "ATTR_", &attrs);
    out.push('\n');
    consts(&mut out, "NS_", &nss);

    // SAFETY: static ids below each table's `_LAST_ENTRY`, which Lexbor answers
    // from its static tables without reading the (null) hash.
    let (tag_names, tag_upper, attr_names, ns_links, ns_prefixes) = unsafe {
        let mut tn = Vec::new();
        let mut tu = Vec::new();
        for id in 0..tag_last {
            let mut len = 0;
            let p = lxb::lxb_tag_name_by_id_noi(id, &mut len);
            tn.push(core::slice::from_raw_parts(p, len).to_vec());
            /* What `lxb_dom_element_qualified_name_upper` interns for an
             * element named by the tag alone (`lexbor_hash_insert_upper`).
             * Not `lxb_tag_name_upper_by_id`: for a static id that answers
             * the static entry, which is lower case. */
            tu.push(core::slice::from_raw_parts(p, len).to_ascii_uppercase());
        }
        let an: Vec<Vec<u8>> = (0..attr_last)
            .map(|id| entry_str(&(*lxb::lxb_dom_attr_data_by_id(core::ptr::null_mut(), id)).entry))
            .collect();
        let nl: Vec<Vec<u8>> = (0..ns_last)
            .map(|id| entry_str(&(*lxb::lxb_ns_data_by_id(core::ptr::null_mut(), id)).entry))
            .collect();
        let np: Vec<Vec<u8>> = (0..ns_last)
            .map(|id| entry_str(&(*lxb::lxb_ns_prefix_data_by_id(core::ptr::null_mut(), id)).entry))
            .collect();
        (tn, tu, an, nl, np)
    };
    let table = |out: &mut String, doc: &str, name: &str, len: &str, v: &[Vec<u8>]| {
        let _ = writeln!(out, "\n/// {doc}\npub const {name}: [&[u8]; {len}] = [");
        for s in v {
            let _ = writeln!(out, "    {},", lit(s));
        }
        out.push_str("];\n");
    };
    table(
        &mut out,
        "Each tag id's name, lower case.",
        "TAG_NAMES",
        "TAG__LAST_ENTRY",
        &tag_names,
    );
    table(
        &mut out,
        "Each tag id's name in ASCII upper case (an HTML element's `tagName`).",
        "TAG_UPPER_NAMES",
        "TAG__LAST_ENTRY",
        &tag_upper,
    );
    table(
        &mut out,
        "Each attribute id's local name, lower case.",
        "ATTR_NAMES",
        "ATTR__LAST_ENTRY",
        &attr_names,
    );
    table(
        &mut out,
        "Each namespace id's URI.",
        "NS_LINKS",
        "NS__LAST_ENTRY",
        &ns_links,
    );
    table(
        &mut out,
        "Each namespace id's prefix.",
        "NS_PREFIXES",
        "NS__LAST_ENTRY",
        &ns_prefixes,
    );
    let by_name = |out: &mut String, doc: &str, name: &str, v: &[Vec<u8>], first: usize| {
        let mut sorted: Vec<(&Vec<u8>, usize)> = v.iter().zip(0..).skip(first).collect();
        sorted.sort();
        let _ = writeln!(
            out,
            "\n/// {doc}\npub static {name}: [(&[u8], usize); {}] = [",
            sorted.len()
        );
        for (n, id) in sorted {
            let _ = writeln!(out, "    ({}, {id}),", lit(n));
        }
        out.push_str("];\n");
    };
    /* Every static id, the special ones included: Lexbor's static lookup
     * (`lexbor_shs_entry_get_lower_static`) holds them all, so an attribute
     * named `#undef` resolves to id 0 there, and here. */
    by_name(
        &mut out,
        "Static tag names to tag ids, sorted by name.",
        "TAG_BY_NAME",
        &tag_names,
        0,
    );
    by_name(
        &mut out,
        "Static attribute local names to attribute ids, sorted by name.",
        "ATTR_BY_NAME",
        &attr_names,
        0,
    );
    out
}

/// Lexbor's own tree, read from `res.h`: `{0x61, "\x..", 2, 3, 2, 53}`.
fn lexbor_entities() -> Vec<crate::conformance::res_gen::SbstOwned> {
    let text = std::fs::read_to_string(lexbor_src("html/tokenizer/res.h")).expect("res.h");
    let body = &text[text
        .find("lxb_html_tokenizer_res_entities_sbst[]")
        .expect("the table")..];
    let mut out = Vec::new();
    let mut rest = &body[body.find('{').expect("open") + 1..];
    while let Some(start) = rest.find('{') {
        let end = rest[start..].find('}').expect("entry end") + start;
        let fields: Vec<&str> = rest[start + 1..end].split(", ").collect();
        let num = |s: &str| {
            let s = s.trim();
            match s.strip_prefix("0x") {
                Some(h) => usize::from_str_radix(h, 16).expect("hex"),
                None => s.parse().expect("number"),
            }
        };
        let value = match fields[1].trim() {
            "NULL" => None,
            q => {
                let inner = q.trim_matches('"');
                Some(
                    inner
                        .split("\\x")
                        .filter(|h| !h.is_empty())
                        .map(|h| u8::from_str_radix(h, 16).expect("byte"))
                        .collect(),
                )
            }
        };
        out.push(crate::conformance::res_gen::SbstOwned {
            key: num(fields[0]) as u8,
            value,
            left: num(fields[3]),
            right: num(fields[4]),
            next: num(fields[5]),
        });
        rest = &rest[end + 1..];
        if rest.trim_start().starts_with("};") {
            break;
        }
    }
    out
}

/* ---- the tree builder's tables (`html/tag_res.h`, `html/tree_res.h`) ---- */

/// The text of a C array initialiser: what follows `name` up to its `};`,
/// with comments dropped.
fn c_array_body(text: &str, name: &str) -> String {
    let at = text.find(name).expect("the array in the header");
    let rest = &text[at..];
    let open = rest.find('=').expect("an initialiser") + 1;
    let close = rest.find("};").expect("the initialiser's end");
    let mut body = String::new();
    let mut src = &rest[open..close];
    while let Some(c) = src.find("/*") {
        body.push_str(&src[..c]);
        let e = src[c..].find("*/").expect("a closed comment");
        src = &src[c + e + 2..];
    }
    body.push_str(src);
    body
}

/// The rows of an initialiser body - its `{ ... }` groups one level in -
/// each as its text.
fn c_groups(body: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut depth = 0;
    let mut cur = String::new();
    for ch in body.chars() {
        match ch {
            '{' => {
                depth += 1;
                cur.clear();
            }
            '}' => {
                if depth == 2 {
                    out.push(cur.trim().to_string());
                }
                depth -= 1;
            }
            c if depth == 2 => cur.push(c),
            _ => {}
        }
    }
    out
}

/// A C string literal's bytes, or empty for `NULL`.
fn c_str(field: &str) -> Vec<u8> {
    match (field.find('"'), field.rfind('"')) {
        (Some(a), Some(b)) if b > a => field[a + 1..b].as_bytes().to_vec(),
        _ => Vec::new(),
    }
}

/// Lexbor's tree builder tables, read from `tag_res.h` and `tree_res.h`:
/// the categories per static tag and namespace, the SVG tag names, and the
/// two attribute adjustment maps.
struct LexborTreeTables {
    cats: Vec<Vec<u8>>,
    svg_fixname: Vec<Vec<u8>>,
    svg_attrs: Vec<(Vec<u8>, Vec<u8>)>,
    foreign: Vec<(Vec<u8>, Vec<u8>, Vec<u8>, usize)>,
}

fn lexbor_tree_tables() -> LexborTreeTables {
    let tag_res = std::fs::read_to_string(lexbor_src("html/tag_res.h")).expect("tag_res.h");
    let tree_res = std::fs::read_to_string(lexbor_src("html/tree_res.h")).expect("tree_res.h");
    let cat_names = enum_consts(&lexbor_src("html/tag.h"), "LXB_HTML_TAG_CATEGORY_");
    let cat_value = |name: &str| -> u8 {
        let name = name
            .trim()
            .strip_prefix("LXB_HTML_TAG_CATEGORY_")
            .expect("a category");
        cat_names
            .iter()
            .find(|(n, _)| n == name)
            .map(|(_, v)| *v as u8)
            .expect("a known category")
    };
    let cats = c_groups(&c_array_body(&tag_res, "lxb_html_tag_res_cats["))
        .iter()
        .map(|row| {
            row.split(',')
                .filter(|e| !e.trim().is_empty())
                .map(|e| e.split('|').map(cat_value).fold(0, |a, b| a | b))
                .collect()
        })
        .collect();
    let svg_fixname = c_groups(&c_array_body(&tag_res, "lxb_html_tag_res_fixname_svg["))
        .iter()
        .map(|row| c_str(row))
        .collect();
    let svg_attrs = c_groups(&c_array_body(
        &tree_res,
        "lxb_html_tree_res_attr_adjust_svg_map[]",
    ))
    .iter()
    .map(|row| {
        let f: Vec<&str> = row.split(',').collect();
        (c_str(f[0]), c_str(f[1]))
    })
    .collect();
    let nss = enum_consts(&lexbor_src("ns/const.h"), "LXB_NS_");
    let foreign = c_groups(&c_array_body(
        &tree_res,
        "lxb_html_tree_res_attr_adjust_foreign_map[]",
    ))
    .iter()
    .map(|row| {
        let f: Vec<&str> = row.split(',').map(str::trim).collect();
        let ns = f[5].strip_prefix("LXB_NS_").expect("a namespace");
        let ns = nss
            .iter()
            .find(|(n, _)| n == ns)
            .map(|(_, v)| *v)
            .expect("known");
        (c_str(f[0]), c_str(f[1]), c_str(f[2]), ns)
    })
    .collect();
    LexborTreeTables {
        cats,
        svg_fixname,
        svg_attrs,
        foreign,
    }
}

/// `html::res::tree` - generated from the HTML Standard
/// (`conformance::res_gen`) - says what Lexbor's tables say, but for the one
/// entry the Standard leaves out on purpose: Lexbor counts HTML `image` as
/// special, an element the parser never puts on the stack ("so it doesn't
/// matter"), so no answer depends on it. The ordinary bit is not compared:
/// the Standard defines it as neither special nor formatting, Lexbor sets it
/// its own way, and nothing asks for it.
#[test]
fn tree_tables_agree_with_lexbors() {
    use crate::html::res::tree as rt;
    let l = lexbor_tree_tables();
    for (tag, (lrow, row)) in l.cats.iter().zip(rt::TAG_CATS.iter()).enumerate() {
        for (ns, (&lc, &c)) in lrow.iter().zip(row.iter()).enumerate() {
            let mut lc = lc & !rt::CAT_ORDINARY;
            if tag == names::TAG_IMAGE && ns == names::NS_HTML {
                lc &= !rt::CAT_SPECIAL;
            }
            assert_eq!(
                lc,
                c & !rt::CAT_ORDINARY,
                "categories of {} in namespace {ns}",
                String::from_utf8_lossy(names::TAG_NAMES[tag])
            );
        }
    }
    assert_eq!(l.cats.len(), rt::TAG_CATS.len());
    let fix: Vec<Vec<u8>> = rt::SVG_FIXNAME.iter().map(|f| f.to_vec()).collect();
    assert_eq!(l.svg_fixname, fix, "the SVG tag names");
    let mut ours: Vec<(Vec<u8>, Vec<u8>)> = rt::SVG_ATTR_ADJUST
        .iter()
        .map(|(a, b)| (a.to_vec(), b.to_vec()))
        .collect();
    let mut theirs = l.svg_attrs;
    ours.sort();
    theirs.sort();
    assert_eq!(theirs, ours, "the SVG attribute names");
    let ours: Vec<_> = rt::FOREIGN_ATTR_ADJUST
        .iter()
        .map(|(a, b, c, ns)| (a.to_vec(), b.to_vec(), c.to_vec(), *ns))
        .collect();
    assert_eq!(l.foreign, ours, "the foreign attributes");
}

fn check_or_write(rel: &str, generated: &str) {
    let path = root().join("src/html/res").join(rel);
    if std::env::var_os("MAKIRI_REGENERATE").is_some() {
        std::fs::write(&path, generated).expect("write a generated table");
        return;
    }
    let current = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        current == generated,
        "{} is not what the generator makes now - rerun with MAKIRI_REGENERATE=1",
        path.display()
    );
}

#[test]
fn names_are_lexbors() {
    check_or_write("names.rs", &generate_names());
}

