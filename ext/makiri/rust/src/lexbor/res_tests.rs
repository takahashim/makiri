//! The generator of `html::res`, and its oracle.
//!
//! `html::res::names` is built from Lexbor's static tables: the constant names
//! from the enum headers (`tag/const.h`, `dom/interfaces/attr_const.h`,
//! `ns/const.h`) and each id's strings from the linked Lexbor itself.
//! `html::res::entities` is built from the WHATWG `entities.json` (pinned by
//! digest in `spec/conformance/parser_data.rb`) with a port of Lexbor's
//! `utils/lexbor/html/tokenizer_entities_bst.py`, and then compared with the
//! tree Lexbor generated from its own copy (`html/tokenizer/res.h`).
//!
//! The tests fail when a checked-in file is not what the generator makes now;
//! `MAKIRI_REGENERATE=1` rewrites them instead.

#![allow(unsafe_code)]
#![allow(clippy::disallowed_methods)]

use crate::html::res::{entities, names, SbstEntry};
use crate::lexbor::abi as lxb;
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn lexbor_src(rel: &str) -> PathBuf {
    root()
        .join("../../../vendor/lexbor/source/lexbor")
        .join(rel)
}

/// `NAME = 0x00NN` pairs of the enum whose constants start with `prefix`.
fn enum_consts(header: &Path, prefix: &str) -> Vec<(String, usize)> {
    let text = std::fs::read_to_string(header).expect("read a Lexbor header");
    text.lines()
        .filter_map(|l| {
            let l = l.trim().trim_end_matches(',');
            let (name, value) = l.split_once('=')?;
            let name = name.trim().strip_prefix(prefix)?;
            let value = value.trim().strip_prefix("0x")?;
            Some((name.to_string(), usize::from_str_radix(value, 16).ok()?))
        })
        .collect()
}

/// The string of a Lexbor hash entry.
///
/// # Safety
/// `e` is a live entry.
unsafe fn entry_str(e: &lxb::lexbor_hash_entry_t) -> Vec<u8> {
    // SAFETY: the function's contract; an entry keeps a string up to
    // LEXBOR_HASH_SHORT_SIZE (16) inline and a longer one by pointer.
    unsafe {
        if e.length <= 16 {
            e.u.short_str[..e.length].to_vec()
        } else {
            core::slice::from_raw_parts(e.u.long_str, e.length).to_vec()
        }
    }
}

fn lit(b: &[u8]) -> String {
    let mut s = String::from("b\"");
    for &c in b {
        match c {
            b'"' | b'\\' => {
                s.push('\\');
                s.push(c as char);
            }
            0x20..=0x7e => s.push(c as char),
            _ => {
                let _ = write!(s, "\\x{c:02x}");
            }
        }
    }
    s.push('"');
    s
}

/// One constant block: `pub const PREFIX_NAME: usize = N;` per enum entry.
fn consts(out: &mut String, rust_prefix: &str, entries: &[(String, usize)]) {
    for (name, v) in entries {
        let _ = writeln!(out, "pub const {rust_prefix}{name}: usize = {v};");
    }
}

fn generate_names() -> String {
    let tags = enum_consts(&lexbor_src("tag/const.h"), "LXB_TAG_");
    let attrs = enum_consts(&lexbor_src("dom/interfaces/attr_const.h"), "LXB_DOM_ATTR_");
    let nss = enum_consts(&lexbor_src("ns/const.h"), "LXB_NS_");
    let last = |v: &[(String, usize)]| {
        v.iter()
            .find(|(n, _)| n == "_LAST_ENTRY")
            .map(|(_, v)| *v)
            .expect("a _LAST_ENTRY")
    };
    let (tag_last, attr_last, ns_last) = (last(&tags), last(&attrs), last(&nss));
    let mut out = String::from(
        "//! GENERATED by `lexbor::res_tests` from Lexbor's static name tables - do not edit.\n\
         //! Ids are Lexbor's: `TAG_*` from `tag/const.h`, `ATTR_*` from\n\
         //! `dom/interfaces/attr_const.h`, `NS_*` from `ns/const.h`.\n\n",
    );
    consts(&mut out, "TAG_", &tags);
    out.push('\n');
    consts(&mut out, "ATTR_", &attrs);
    out.push('\n');
    consts(&mut out, "NS_", &nss);

    // SAFETY: static ids below each table's `_LAST_ENTRY`, which Lexbor answers
    // from its static tables without reading the (null) hash.
    let (tag_names, tag_upper, attr_names, ns_links, ns_prefixes) = unsafe {
        let mut tn = Vec::new();
        let mut tu = Vec::new();
        for id in 0..tag_last {
            let mut len = 0;
            let p = lxb::lxb_tag_name_by_id_noi(id, &mut len);
            tn.push(core::slice::from_raw_parts(p, len).to_vec());
            let p = lxb::lxb_tag_name_upper_by_id_noi(id, &mut len);
            tu.push(if p.is_null() {
                Vec::new()
            } else {
                core::slice::from_raw_parts(p, len).to_vec()
            });
        }
        let an: Vec<Vec<u8>> = (0..attr_last)
            .map(|id| entry_str(&(*lxb::lxb_dom_attr_data_by_id(core::ptr::null_mut(), id)).entry))
            .collect();
        let nl: Vec<Vec<u8>> = (0..ns_last)
            .map(|id| entry_str(&(*lxb::lxb_ns_data_by_id(core::ptr::null_mut(), id)).entry))
            .collect();
        let np: Vec<Vec<u8>> = (0..ns_last)
            .map(|id| entry_str(&(*lxb::lxb_ns_prefix_data_by_id(core::ptr::null_mut(), id)).entry))
            .collect();
        (tn, tu, an, nl, np)
    };
    let table = |out: &mut String, doc: &str, name: &str, len: &str, v: &[Vec<u8>]| {
        let _ = writeln!(out, "\n/// {doc}\npub static {name}: [&[u8]; {len}] = [");
        for s in v {
            let _ = writeln!(out, "    {},", lit(s));
        }
        out.push_str("];\n");
    };
    table(
        &mut out,
        "Each tag id's name, lower case.",
        "TAG_NAMES",
        "TAG__LAST_ENTRY",
        &tag_names,
    );
    table(
        &mut out,
        "Each tag id's upper-case name (the HTML `tagName`).",
        "TAG_UPPER_NAMES",
        "TAG__LAST_ENTRY",
        &tag_upper,
    );
    table(
        &mut out,
        "Each attribute id's local name, lower case.",
        "ATTR_NAMES",
        "ATTR__LAST_ENTRY",
        &attr_names,
    );
    table(
        &mut out,
        "Each namespace id's URI.",
        "NS_LINKS",
        "NS__LAST_ENTRY",
        &ns_links,
    );
    table(
        &mut out,
        "Each namespace id's prefix.",
        "NS_PREFIXES",
        "NS__LAST_ENTRY",
        &ns_prefixes,
    );
    let by_name = |out: &mut String, doc: &str, name: &str, v: &[Vec<u8>], first: usize| {
        let mut sorted: Vec<(&Vec<u8>, usize)> = v.iter().zip(0..).skip(first).collect();
        sorted.sort();
        let _ = writeln!(
            out,
            "\n/// {doc}\npub static {name}: [(&[u8], usize); {}] = [",
            sorted.len()
        );
        for (n, id) in sorted {
            let _ = writeln!(out, "    ({}, {id}),", lit(n));
        }
        out.push_str("];\n");
    };
    /* Every static id, the special ones included: Lexbor's static lookup
     * (`lexbor_shs_entry_get_lower_static`) holds them all, so an attribute
     * named `#undef` resolves to id 0 there, and here. */
    by_name(
        &mut out,
        "Static tag names to tag ids, sorted by name.",
        "TAG_BY_NAME",
        &tag_names,
        0,
    );
    by_name(
        &mut out,
        "Static attribute local names to attribute ids, sorted by name.",
        "ATTR_BY_NAME",
        &attr_names,
        0,
    );
    out
}

/* ---- the entity tree, ported from tokenizer_entities_bst.py ---- */

#[derive(Default)]
struct Layer(BTreeMap<u8, LayerEntry>);

#[derive(Default)]
struct LayerEntry {
    next: Layer,
    values: Vec<Vec<u8>>,
}

struct Node {
    key: u8,
    left: usize,
    right: usize,
    next: usize,
    value: Option<Vec<u8>>,
    pending: Option<Layer>,
}

/// `entities_bst_create_tree`: lay out one layer from `idx`, returning the
/// next free index. The arithmetic is the script's, step for step.
fn create_tree(index: Layer, bst: &mut BTreeMap<usize, Node>, mut idx: usize) -> usize {
    let mut index = index.0;
    let mut keys: Vec<u8> = index.keys().copied().collect();
    let mut optv: Vec<(Vec<u8>, usize)> = Vec::new();
    let mut inr: Option<usize> = None;
    while !keys.is_empty() {
        let mid = keys.len() / 2;
        let (key, left_keys, right_keys) =
            (keys[mid], keys[..mid].to_vec(), keys[mid + 1..].to_vec());
        let mut idx_left = if left_keys.is_empty() { 0 } else { idx + 2 };
        let idx_right = if right_keys.is_empty() { 0 } else { idx + 1 };
        if idx_right == 0 && idx_left != 0 {
            idx_left -= 1;
        }
        let at = match inr {
            Some(parent) => bst[&parent].right,
            None => idx,
        };
        let entry = index.remove(&key).expect("a key of this layer");
        assert!(entry.values.len() < 2, "double values");
        bst.insert(
            at,
            Node {
                key,
                left: idx_left,
                right: idx_right,
                next: 0,
                value: entry.values.into_iter().next(),
                pending: Some(entry.next),
            },
        );
        if !right_keys.is_empty() {
            optv.push((right_keys, at));
        }
        if idx_left != 0 {
            idx = idx_left;
        }
        inr = None;
        keys = left_keys;
        if keys.is_empty() {
            let Some((k, parent)) = optv.pop() else { break };
            keys = k;
            inr = Some(parent);
        }
    }
    idx + 1
}

/// `entities_bst_create`: every layer, depth first.
fn create_bst(index: Layer) -> BTreeMap<usize, Node> {
    let mut bst = BTreeMap::new();
    bst.insert(
        0,
        Node {
            key: 0,
            left: 0,
            right: 0,
            next: 0,
            value: None,
            pending: None,
        },
    );
    let mut begin = 1;
    let mut end = create_tree(index, &mut bst, begin);
    let mut idx = end;
    let mut stack = Vec::new();
    loop {
        while begin < end {
            let node = bst.get_mut(&begin).expect("a laid-out node");
            match node.pending.take() {
                Some(layer) if !layer.0.is_empty() => {
                    node.next = idx;
                    stack.push((begin + 1, end));
                    begin = idx;
                    idx = create_tree(layer, &mut bst, idx);
                    end = idx;
                }
                _ => begin += 1,
            }
        }
        let Some((b, e)) = stack.pop() else { break };
        begin = b;
        end = e;
    }
    bst
}

fn entities_json() -> PathBuf {
    root().join("../../../spec/conformance/data/whatwg/entities.json")
}

fn build_entities() -> Vec<SbstOwned> {
    let text = std::fs::read_to_string(entities_json())
        .expect("entities.json - run `ruby spec/conformance/parser_data.rb`");
    let json = crate::conformance::json::parse(&text).expect("entities.json parses");
    let crate::conformance::json::Json::Obj(map) = json else {
        panic!("entities.json is an object")
    };
    let mut index = Layer::default();
    for (name, v) in &map {
        let chars = v
            .get("characters")
            .and_then(|c| c.as_str())
            .expect("characters")
            .bytes
            .clone();
        let name = name.as_bytes();
        let mut layer = &mut index;
        for (pos, &c) in name.iter().enumerate().skip(1) {
            let e = layer.0.entry(c).or_default();
            if pos == name.len() - 1 {
                e.values.push(chars.clone());
            }
            layer = &mut e.next;
        }
    }
    let bst = create_bst(index);
    let n = bst.keys().last().copied().unwrap_or(0) + 1;
    assert_eq!(bst.len(), n, "the tree's indices are contiguous");
    bst.into_values()
        .map(|n| SbstOwned {
            key: n.key,
            value: n.value,
            left: n.left,
            right: n.right,
            next: n.next,
        })
        .collect()
}

#[derive(Debug, PartialEq, Eq)]
struct SbstOwned {
    key: u8,
    value: Option<Vec<u8>>,
    left: usize,
    right: usize,
    next: usize,
}

fn generate_entities(table: &[SbstOwned]) -> String {
    let mut out = String::from(
        "//! GENERATED by `lexbor::res_tests` from the WHATWG entities.json - do not edit.\n\
         //! The named character references as Lexbor's static search tree\n\
         //! (`html/tokenizer/res.h`), one byte per layer after the `&`.\n\n\
         use super::SbstEntry;\n\n\
         const fn e(key: u8, value: Option<&'static [u8]>, left: u16, right: u16, next: u16) -> SbstEntry {\n    \
         SbstEntry { key, value, left, right, next }\n}\n\n",
    );
    let _ = writeln!(out, "pub static ENTITIES: [SbstEntry; {}] = [", table.len());
    for t in table {
        let v = t
            .value
            .as_deref()
            .map(|v| format!("Some({})", lit(v)))
            .unwrap_or_else(|| "None".to_string());
        let _ = writeln!(
            out,
            "    e(0x{:02x}, {v}, {}, {}, {}),",
            t.key, t.left, t.right, t.next
        );
    }
    out.push_str("];\n");
    out
}

/// Lexbor's own tree, read from `res.h`: `{0x61, "\x..", 2, 3, 2, 53}`.
fn lexbor_entities() -> Vec<SbstOwned> {
    let text = std::fs::read_to_string(lexbor_src("html/tokenizer/res.h")).expect("res.h");
    let body = &text[text
        .find("lxb_html_tokenizer_res_entities_sbst[]")
        .expect("the table")..];
    let mut out = Vec::new();
    let mut rest = &body[body.find('{').expect("open") + 1..];
    while let Some(start) = rest.find('{') {
        let end = rest[start..].find('}').expect("entry end") + start;
        let fields: Vec<&str> = rest[start + 1..end].split(", ").collect();
        let num = |s: &str| {
            let s = s.trim();
            match s.strip_prefix("0x") {
                Some(h) => usize::from_str_radix(h, 16).expect("hex"),
                None => s.parse().expect("number"),
            }
        };
        let value = match fields[1].trim() {
            "NULL" => None,
            q => {
                let inner = q.trim_matches('"');
                Some(
                    inner
                        .split("\\x")
                        .filter(|h| !h.is_empty())
                        .map(|h| u8::from_str_radix(h, 16).expect("byte"))
                        .collect(),
                )
            }
        };
        out.push(SbstOwned {
            key: num(fields[0]) as u8,
            value,
            left: num(fields[3]),
            right: num(fields[4]),
            next: num(fields[5]),
        });
        rest = &rest[end + 1..];
        if rest.trim_start().starts_with("};") {
            break;
        }
    }
    out
}

fn check_or_write(rel: &str, generated: &str) {
    let path = root().join("src/html/res").join(rel);
    if std::env::var_os("MAKIRI_REGENERATE").is_some() {
        std::fs::write(&path, generated).expect("write a generated table");
        return;
    }
    let current = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        current == generated,
        "{} is not what the generator makes now - rerun with MAKIRI_REGENERATE=1",
        path.display()
    );
}

#[test]
fn names_are_lexbors() {
    check_or_write("names.rs", &generate_names());
}

#[test]
fn entities_are_the_whatwg_list_in_lexbors_tree() {
    let built = build_entities();
    assert_eq!(
        built,
        lexbor_entities(),
        "the tree built from entities.json is not Lexbor's"
    );
    check_or_write("entities.rs", &generate_entities(&built));
}

#[test]
fn the_generated_tables_answer_like_lexbor() {
    use crate::html::res::{attr_id_by_lower_name, ns_id_by_link, sbst_find, tag_id_by_lower_name};
    assert_eq!(
        tag_id_by_lower_name(b"div"),
        Some(lxb::lxb_tag_id_enum_t_LXB_TAG_DIV as usize)
    );
    assert_eq!(
        tag_id_by_lower_name(b"annotation-xml"),
        Some(names::TAG_ANNOTATION_XML)
    );
    assert_eq!(tag_id_by_lower_name(b"#text"), Some(names::TAG__TEXT));
    assert_eq!(attr_id_by_lower_name(b"#undef"), Some(names::ATTR__UNDEF));
    assert_eq!(
        attr_id_by_lower_name(b"class"),
        Some(lxb::lxb_dom_attr_id_enum_t_LXB_DOM_ATTR_CLASS as usize)
    );
    assert_eq!(
        ns_id_by_link(b"http://www.w3.org/2000/svg"),
        Some(names::NS_SVG)
    );
    /* `&amp;` walks a, m, p, ; from the root layer at index 1. */
    let t: &'static [SbstEntry] = &entities::ENTITIES;
    let mut root = 1;
    let mut last = None;
    for &c in b"amp;" {
        let e = &t[sbst_find(t, root, c).expect("a step of &amp;")];
        last = e.value;
        root = e.next as usize;
    }
    assert_eq!(last, Some(&b"&"[..]));
}
